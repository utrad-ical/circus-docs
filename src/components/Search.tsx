'use client';

import { useEffect, useRef, useState } from 'react';
import { useRouter } from 'waku';
import { SearchIcon } from './icons.tsx';
import styles from './Search.module.css';

type SubResult = { title: string; url: string; excerpt: string };

type Result = {
  url: string;
  excerpt: string;
  meta: { title?: string };
  sub_results: SubResult[];
};

type Pagefind = {
  init: () => Promise<void>;
  debouncedSearch: (
    query: string
  ) => Promise<{ results: { data: () => Promise<Result> }[] } | null>;
};

// The index is generated after the build (scripts/postbuild.ts),
// so the bundler must not try to resolve this.
const pagefindPath = '/pagefind/pagefind.js';

let pagefindPromise: Promise<Pagefind | null> | undefined;

const loadPagefind = () => {
  pagefindPromise ??= import(/* @vite-ignore */ pagefindPath).then(
    async (pagefind: Pagefind) => {
      await pagefind.init();
      return pagefind;
    },
    () => null
  );
  return pagefindPromise;
};

const maxResults = 8;

/** Pagefind returns the URL of the HTML file, like `/docs/users/login/`. */
const toRoute = (url: string) => url.replace(/\/(?=#|$)/, '') || '/';

const Search = () => {
  const dialogRef = useRef<HTMLDialogElement>(null);
  const [query, setQuery] = useState('');
  const [results, setResults] = useState<Result[] | null>(null);
  const [unavailable, setUnavailable] = useState(false);
  const router = useRouter();

  const open = () => {
    dialogRef.current?.showModal();
    loadPagefind().then(pagefind => setUnavailable(!pagefind));
  };

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      const target = e.target as HTMLElement;
      const typing =
        /^(INPUT|TEXTAREA|SELECT)$/.test(target.tagName) ||
        target.isContentEditable;
      const shortcut =
        (e.key === 'k' && (e.ctrlKey || e.metaKey)) ||
        (e.key === '/' && !typing);
      if (!shortcut || dialogRef.current?.open) return;
      e.preventDefault();
      open();
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, []);

  useEffect(() => {
    let stale = false;
    (async () => {
      if (query.trim() === '') return setResults(null);
      const pagefind = await loadPagefind();
      if (!pagefind || stale) return;
      // Resolves to null when a newer search has started
      const search = await pagefind.debouncedSearch(query);
      if (!search || stale) return;
      const data = await Promise.all(
        search.results.slice(0, maxResults).map(r => r.data())
      );
      if (!stale) setResults(data);
    })();
    return () => {
      stale = true;
    };
  }, [query]);

  const navigate = (url: string) => {
    dialogRef.current?.close();
    router.push(toRoute(url));
  };

  const handleLinkClick = (e: React.MouseEvent<HTMLAnchorElement>) => {
    if (e.button !== 0 || e.ctrlKey || e.metaKey || e.shiftKey) return;
    e.preventDefault();
    navigate(e.currentTarget.getAttribute('href')!);
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    const first = results?.[0];
    if (first) navigate(first.sub_results[0]?.url ?? first.url);
  };

  return (
    <>
      <button
        type="button"
        className={styles.button}
        onClick={open}
        aria-label="Search"
      >
        <SearchIcon size={18} />
        <span className={styles.buttonLabel}>Search</span>
        <kbd className={styles.shortcut}>/</kbd>
      </button>
      <dialog
        ref={dialogRef}
        className={styles.dialog}
        aria-label="Search the docs"
        onClick={e => {
          // A click on the backdrop lands on the dialog element itself
          if (e.target === e.currentTarget) e.currentTarget.close();
        }}
      >
        <form className={styles.form} onSubmit={handleSubmit}>
          <SearchIcon />
          <input
            type="search"
            className={styles.input}
            placeholder="Search the docs"
            aria-label="Search the docs"
            value={query}
            onChange={e => setQuery(e.target.value)}
            autoFocus
          />
        </form>
        <div className={styles.results}>
          {unavailable && (
            <p className={styles.message}>
              The search index is not available. It is generated by the
              production build.
            </p>
          )}
          {results?.length === 0 && (
            <p className={styles.message}>No results for “{query}”.</p>
          )}
          {results?.map(result => (
            <section key={result.url} className={styles.result}>
              <a
                href={toRoute(result.url)}
                className={styles.pageTitle}
                onClick={handleLinkClick}
              >
                {result.meta.title}
              </a>
              {result.sub_results.slice(0, 3).map(sub => (
                <a
                  key={sub.url}
                  href={toRoute(sub.url)}
                  className={styles.subResult}
                  onClick={handleLinkClick}
                >
                  {sub.title !== result.meta.title && (
                    <span className={styles.subTitle}>{sub.title}</span>
                  )}
                  <span
                    className={styles.excerpt}
                    // Pagefind marks the matches with <mark> in the excerpt
                    dangerouslySetInnerHTML={{ __html: sub.excerpt }}
                  />
                </a>
              ))}
            </section>
          ))}
        </div>
      </dialog>
    </>
  );
};

export default Search;
